#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(CDPATH= cd -- "${SCRIPT_DIR}/.." && pwd)"
export ROOT_DIR
TOVEN="${TOVEN:-toven}"

if [[ -n "${PYTHON:-}" ]]; then
  PYTHON_BIN="$PYTHON"
elif command -v python3.14 >/dev/null 2>&1; then
  PYTHON_BIN="python3.14"
elif command -v python3.13 >/dev/null 2>&1; then
  PYTHON_BIN="python3.13"
elif command -v python3.12 >/dev/null 2>&1; then
  PYTHON_BIN="python3.12"
elif command -v python3.11 >/dev/null 2>&1; then
  PYTHON_BIN="python3.11"
else
  PYTHON_BIN="python3"
fi

if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
  echo "Python 3.11+ is required" >&2
  exit 1
fi

# Domains are toven.toml [groups.*]; Toven validates their layering and
# resolves members, so the index reads them from Toven instead of a second list.
"$TOVEN" groups --output jsonl | "$PYTHON_BIN" -c '
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

if sys.version_info < (3, 11):
    raise SystemExit("Python 3.11+ is required")

DOMAIN_EMOJI = {
    "foundation": "🧱",
    "composition": "🏗️",
    "devtools": "🛠️",
    "transport": "🌐",
    "auth": "🔑",
    "data": "💾",
    "ai": "🧠",
    "media": "🎬",
    "infra": "⚙️",
}
DOMAIN_TITLES = {"ai": "AI"}


def layered(groups: dict[str, dict]) -> list[str]:
    """Group names with every group after the groups it may depend on."""
    ordered: list[str] = []
    remaining = dict(groups)
    while remaining:
        ready = sorted(
            name
            for name, group in remaining.items()
            if all(dep in ordered for dep in (group["allow_groups"] or []))
        )
        if not ready:
            raise SystemExit(f"cyclic allow_groups between: {sorted(remaining)}")
        ordered.extend(ready)
        for name in ready:
            del remaining[name]
    return ordered


groups = {record["group"]: record for record in map(json.loads, sys.stdin)}
if not groups:
    raise SystemExit("toven groups returned no groups; declare [groups.*] in toven.toml")

lines = [
    "# Module Index by Domain",
    "",
    "<!-- Auto-generated by scripts/generate-module-index.sh from `toven groups` — do not edit manually -->",
    "",
    "Domains are `[groups.*]` in `toven.toml`, listed lowest layer first. Run one with `make check-<domain>`.",
    "",
]
for name in layered(groups):
    group = groups[name]
    emoji = DOMAIN_EMOJI.get(name, "📦")
    title = DOMAIN_TITLES.get(name, name.replace("-", " ").title())
    lines.append(f"## {emoji} {title}  (`make check-{name}`)")
    if group["description"]:
        lines.append(group["description"])
        lines.append("")
    lines.append(" · ".join("gokit (root)" if m["path"] == "." else m["path"] for m in group["members"]))
    allowed = group["allow_groups"]
    if allowed:
        lines.append("")
        lines.append("May depend on: " + ", ".join(allowed))
    lines.append("")

output_path = Path(os.environ["ROOT_DIR"]) / "docs" / "MODULE-INDEX.md"
output_path.parent.mkdir(parents=True, exist_ok=True)
output_path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
print(f"Generated {output_path}")
'
